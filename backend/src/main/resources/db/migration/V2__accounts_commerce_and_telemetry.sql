CREATE TABLE user_account (
  id VARCHAR(100) PRIMARY KEY, username VARCHAR(40) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL, display_name VARCHAR(60) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('CUSTOMER','ADMIN')),
  enabled BOOLEAN NOT NULL DEFAULT TRUE, phone VARCHAR(30) NOT NULL DEFAULT '',
  shipping_address VARCHAR(300) NOT NULL DEFAULT '', failed_logins INT NOT NULL DEFAULT 0,
  locked_until TIMESTAMP, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE auth_session (
  token_hash VARCHAR(64) PRIMARY KEY, user_id VARCHAR(100) NOT NULL REFERENCES user_account(id),
  expires_at TIMESTAMP NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_session_owner ON auth_session(user_id);
CREATE TABLE wallet (
  user_id VARCHAR(100) PRIMARY KEY REFERENCES user_account(id),
  balance NUMERIC(14,2) NOT NULL CHECK (balance >= 0), version INT NOT NULL DEFAULT 0
);
CREATE TABLE wallet_ledger (
  id VARCHAR(100) PRIMARY KEY, user_id VARCHAR(100) NOT NULL REFERENCES user_account(id),
  business_key VARCHAR(180) NOT NULL UNIQUE, kind VARCHAR(30) NOT NULL,
  order_id VARCHAR(100), amount NUMERIC(14,2) NOT NULL, balance_after NUMERIC(14,2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ledger_owner ON wallet_ledger(user_id,created_at);
CREATE TABLE product_inventory (
  product_id VARCHAR(100) PRIMARY KEY REFERENCES product(id),
  available INT NOT NULL CHECK (available >= 0), version INT NOT NULL DEFAULT 0
);
CREATE TABLE shop_order (
  id VARCHAR(100) PRIMARY KEY, user_id VARCHAR(100) NOT NULL REFERENCES user_account(id),
  request_key VARCHAR(100) NOT NULL, request_hash VARCHAR(64) NOT NULL,
  status VARCHAR(30) NOT NULL, amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
  funding_source VARCHAR(30) NOT NULL CHECK (funding_source IN ('WALLET','LEGACY_DEMO')),
  recipient VARCHAR(60) NOT NULL, phone VARCHAR(30) NOT NULL, address VARCHAR(300) NOT NULL,
  tracking_number VARCHAR(80) NOT NULL DEFAULT '', refund_previous_status VARCHAR(30), version INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, shipped_at TIMESTAMP, delivered_at TIMESTAMP,
  UNIQUE(user_id,request_key)
);
CREATE INDEX idx_shop_order_user ON shop_order(user_id,created_at);
CREATE INDEX idx_shop_order_status ON shop_order(status,created_at);
CREATE TABLE order_item (
  order_id VARCHAR(100) NOT NULL REFERENCES shop_order(id), product_id VARCHAR(100) NOT NULL REFERENCES product(id),
  product_name VARCHAR(150) NOT NULL, unit_price NUMERIC(14,2) NOT NULL,
  quantity INT NOT NULL CHECK (quantity BETWEEN 1 AND 20), image VARCHAR(200) NOT NULL,
  PRIMARY KEY(order_id,product_id)
);
CREATE TABLE order_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id VARCHAR(100) NOT NULL REFERENCES shop_order(id),
  status VARCHAR(30) NOT NULL, description VARCHAR(300) NOT NULL, actor_id VARCHAR(100) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
